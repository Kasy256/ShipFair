// `pnpm db:sync-blocklist`: regenerates `public.has_profanity` from src/blocklist.ts and
// obscenity's dataset. Migrations are never edited once applied, so when the generated function
// differs from the newest `*_has_profanity.sql`, this writes a new migration. It always rewrites
// the pgTAP test, whose expected values come from the client filter. `--check` writes nothing and
// exits 1 when a new migration is needed (for CI).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { filterProfanity } from '../src/text.ts';
import { NAME_CORPUS } from './blocklist-corpus.ts';
import { hasProfanitySql } from './blocklist-sql.ts';

const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const MIGRATIONS = join(ROOT, 'supabase', 'migrations');
const TEST_FILE = join(ROOT, 'supabase', 'tests', '06_has_profanity.test.sql');
const SUFFIX = '_has_profanity.sql';

const sqlString = (s: string) => `'${s.replaceAll("'", "''")}'`;

function pgTapTest(): string {
  const cases = NAME_CORPUS.map((input) => {
    const expected = filterProfanity(input).hasProfanity;
    return `select is(public.has_profanity(${sqlString(input)}), ${expected}, ${sqlString(`${input} -> ${expected}`)});`;
  });
  return `-- Generated by \`pnpm db:sync-blocklist\`: the database filter agrees with the client filter
-- (filterProfanity in packages/shared) on every input in scripts/blocklist-corpus.ts.
begin;
select plan(${cases.length});
${cases.join('\n')}
select * from finish();
rollback;
`;
}

function timestamp(now = new Date()): string {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${now.getUTCFullYear()}${p(now.getUTCMonth() + 1)}${p(now.getUTCDate())}${p(now.getUTCHours())}${p(now.getUTCMinutes())}${p(now.getUTCSeconds())}`;
}

const isCheck = process.argv.includes('--check');
const sql = hasProfanitySql();
const latest = readdirSync(MIGRATIONS)
  .filter((f) => f.endsWith(SUFFIX))
  .sort()
  .at(-1);
const isCurrent = latest !== undefined && readFileSync(join(MIGRATIONS, latest), 'utf8') === sql;
const test = pgTapTest();
const isTestCurrent = existsSync(TEST_FILE) && readFileSync(TEST_FILE, 'utf8') === test;

if (isCheck) {
  if (isCurrent && isTestCurrent) {
    console.log(`has_profanity is current (${latest})`);
  } else {
    console.error('has_profanity is out of date: run `pnpm db:sync-blocklist`');
    process.exit(1);
  }
} else {
  if (!isCurrent) {
    const file = `${timestamp()}${SUFFIX}`;
    writeFileSync(join(MIGRATIONS, file), sql);
    console.log(`wrote supabase/migrations/${file}`);
  } else {
    console.log(`has_profanity is current (${latest})`);
  }
  writeFileSync(TEST_FILE, test);
  console.log(`wrote supabase/tests/06_has_profanity.test.sql (${NAME_CORPUS.length} cases)`);
}
