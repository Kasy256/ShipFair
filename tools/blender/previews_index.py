"""art/previews/index.html: one page with every preview image and the key numbers from the reports."""

from __future__ import annotations

import html
import json
from typing import Any

from lib.step import Ctx

def load_report(ctx: Ctx, name: str) -> dict[str, Any]:
    p = ctx.reports / f"{name}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def write_index(ctx: Ctx, sections: dict[str, dict[str, Any]]) -> None:
    chars = load_report(ctx, "characters").get("stats", {}).get("characters", [])
    anim = load_report(ctx, "animations").get("stats", {})
    kit = load_report(ctx, "booth-kit").get("stats", {})
    prop = load_report(ctx, "props").get("stats", {})
    e = html.escape

    def imgs(names: list[str]) -> str:
        return "".join(f'<figure><img src="{e(n)}" alt="{e(n)}" loading="lazy"><figcaption>{e(n)}</figcaption></figure>' for n in names)

    rows = "".join(
        f"<tr><td>{e(c['id'])}</td><td>{c['triangles']['totalWithLargestHair']}</td><td>{c['heightM']}</td>"
        f"<td>{c['deformBones']}</td><td>{e(json.dumps(c['regionFaces']))}</td><td>{len(c['hairs'])}</td></tr>"
        for c in chars)
    clips = "".join(
        f"<tr><td>{e(k)}</td><td>{e(v['status'])}</td><td>{e(v.get('source') or v.get('suggestion', ''))}</td>"
        f"<td>{v.get('hipDriftCm', {}).get('after', '')}</td></tr>" for k, v in anim.get("clips", {}).items())
    parts = "".join(f"<tr><td>{e(k)}</td><td>{v['triangles']}</td><td>{v['budget']}</td></tr>"
                    for k, v in kit.get("parts", {}).items())
    props_rows = "".join(f"<tr><td>{e(p['id'])}</td><td>{p['triangles']}</td><td>{e(str(p['sizeM']))}</td>"
                         f"<td>{e(p['collider'])}</td></tr>" for p in prop.get("props", []))
    avatar = avatar_html(ctx, sections.get("avatar", {}))
    page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>ShipFair art previews</title>
<style>
body{{font:14px/1.45 system-ui,sans-serif;margin:0 auto;max-width:1200px;padding:16px;background:#16171b;color:#e8e8ea}}
h1,h2{{font-weight:600}} figure{{display:inline-block;margin:6px;vertical-align:top}} img{{max-width:100%;width:384px;border-radius:6px;background:#222}}
figcaption{{font-size:12px;color:#9a9ca3}} table{{border-collapse:collapse;margin:8px 0 24px}} td,th{{border-bottom:1px solid #2c2e35;padding:4px 10px;text-align:left}}
.wide img{{width:100%}}
</style></head><body>
<h1>Art previews</h1>
<p>Generated by <code>pnpm art:previews</code>. Review the images, then tune <code>art/config/*.json</code> and re-run <code>pnpm art:build-all</code>. PNGs are not committed.</p>
<div class="wide">{imgs(["contact_sheet.png"])}</div>
<h2>Characters</h2>
<table><tr><th>id</th><th>tris (body + largest hair)</th><th>height m</th><th>bones</th><th>region faces</th><th>hairs</th></tr>{rows}</table>
{imgs(sections.get("characters", {}).get("images", []))}
<h2>Animations</h2>
<p>{anim.get("found", 0)}/{anim.get("required", 14)} clips; max hip drift {anim.get("maxHipDriftCm", "?")} cm.</p>
<table><tr><th>clip</th><th>status</th><th>source / suggestion</th><th>hip drift cm</th></tr>{clips}</table>
<h2>Booth kit</h2>
<p>{kit.get("totalTriangles", "?")} tris total; AO bake {kit.get("bakeTotalSeconds", "?")} s. Slot planes: logo red, screens blue, sign green, spawn yellow, maker orange.</p>
<table><tr><th>part</th><th>tris</th><th>budget</th></tr>{parts}</table>
{imgs(sections.get("booth", {}).get("images", []))}
<h2>Props</h2>
<p>{prop.get("count", 0)} props, each next to a 1.78 m reference figure. Order: {e(", ".join(sections.get("props", {}).get("order", [])))}</p>
<div class="wide">{imgs(sections.get("props", {}).get("images", []))}</div>
<table><tr><th>id</th><th>tris</th><th>size m</th><th>collider</th></tr>{props_rows}</table>
{avatar}
</body></html>
"""
    (ctx.previews / "index.html").write_text(page, encoding="utf-8")


def manifest(ctx: Ctx, kind: str) -> list[dict[str, Any]]:
    p = ctx.export / kind / "manifest.json"
    return json.loads(p.read_text(encoding="utf-8"))["items"] if p.exists() else []


def worst_case(ctx: Ctx) -> list[dict[str, Any]]:
    """Largest triangle count per slot, summed per body: the full-avatar LOD0 worst case."""
    chars = load_report(ctx, "characters").get("stats", {}).get("characters", [])
    budget = json.loads((ctx.art / "contract.json").read_text(encoding="utf-8"))["avatar"]["budgets"]["avatarLod0"]
    rows = []
    for c in chars:
        bid, t = c["id"], c["triangles"]
        parts = {"body": t["body"] + t["eyes"] + t["eyebrows"]}
        for slot in ("top", "bottom", "shoes", "accessory"):
            parts[slot] = max((i["tris"].get(bid, 0) for i in manifest(ctx, "wardrobe") if i["slot"] == slot), default=0)
        for kind in ("hair", "facial", "headwear"):
            parts[kind] = max((i["tris"].get(bid, 0) for i in manifest(ctx, kind)), default=0)
        rows.append({"body": bid, "parts": parts, "total": sum(parts.values()), "budget": budget})
    return rows


def avatar_html(ctx: Ctx, sec: dict[str, Any]) -> str:
    if not sec:
        return "<h2>Avatars</h2><p>No wardrobe or hair exports yet: run pnpm art:wardrobe and pnpm art:hair.</p>"
    e = html.escape

    def imgs(names: list[str], wide: bool = True) -> str:
        cls = ' class="wide"' if wide else ""
        return f"<div{cls}>" + "".join(f'<figure><img src="{e(n)}" alt="{e(n)}" loading="lazy"><figcaption>{e(n)}</figcaption></figure>' for n in names) + "</div>"

    wtests = load_report(ctx, "wardrobe").get("stats", {}).get("tests", {})
    htests = load_report(ctx, "hair").get("stats", {}).get("tests", {})
    wrows = "".join(
        f"<tr><td>{e(i['id'])}</td><td>{e(i['slot'])}</td><td>{e(json.dumps(i['tris']))}</td><td>{e(', '.join(i.get('hidesZones', [])))}</td>"
        f"<td>{wtests.get(i['id'] + '_m', {}).get('poseTest', {}).get('maxPenetrationCm', '')} / {wtests.get(i['id'] + '_f', {}).get('poseTest', {}).get('maxPenetrationCm', '')}</td></tr>"
        for i in manifest(ctx, "wardrobe"))
    hrows = ""
    for kind in ("hair", "facial", "headwear"):
        for i in manifest(ctx, kind):
            pen = [htests.get(f"{kind}/{i['id']}_{s}", {}).get("poseTest", {}).get("maxPenetrationCm", "-") for s in ("m", "f")]
            flags = ", ".join(k for k in ("hidesHair", "capIncompatible") if i.get(k))
            hrows += (f"<tr><td>{kind}</td><td>{e(i['id'])}</td><td>{e(str(i.get('family') or ''))}</td><td>{e(str(i.get('length') or ''))}</td>"
                      f"<td>{e(json.dumps(i['tris']))}</td><td>{pen[0]} / {pen[1]}</td><td>{e(flags)}</td></tr>")
    wc = "".join(f"<tr><td>{e(r['body'])}</td><td>{e(json.dumps(r['parts']))}</td><td>{r['total']}</td><td>{r['budget']}</td></tr>" for r in worst_case(ctx))
    return f"""<h2>Avatars</h2>
<p>Palettes: skin (12), hair, clothing and the harmony groups used by Randomise.</p>
{imgs(sec.get("swatches", []), wide=False)}
<h3>Full-avatar LOD0 worst case</h3>
<table><tr><th>body</th><th>largest per slot</th><th>total</th><th>budget</th></tr>{wc}</table>
<h3>Wardrobe</h3>{imgs(sec.get("wardrobe", []))}
<table><tr><th>id</th><th>slot</th><th>tris</th><th>hides</th><th>pose test max cm (m / f)</th></tr>{wrows}</table>
<h3>Hair catalogue (front and back, by family)</h3>{imgs(sec.get("hair", []))}
<h3>Skin x hair matrix (inclusivity check)</h3><p>12 tones x straight, wavy, curly, coily, protective and buzz styles, both bodies.</p>{imgs(sec.get("matrix", []))}
<h3>Facial hair (4 skin tones)</h3>{imgs(sec.get("facial", []))}
<h3>Headwear, and cap/beanie over 4 hair families</h3>{imgs(sec.get("headwear", []))}
<h3>10 random outfits (harmony groups)</h3>{imgs(sec.get("random", []))}
<h3>Pose sheet (3 outfits x idle, walk, run, jump_air, emote_wave or its substitute, emote_dance)</h3>{imgs(sec.get("poses", []))}
<h3>Catalogue</h3>
<table><tr><th>kind</th><th>id</th><th>family</th><th>length</th><th>tris</th><th>pose test max cm (m / f)</th><th>flags</th></tr>{hrows}</table>
<p>Thumbnails ({e(json.dumps(sec.get("thumbs", {})))}) are in art/export/&lt;kind&gt;/thumbs/.</p>"""
