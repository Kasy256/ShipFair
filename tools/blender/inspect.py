"""art:inspect - inventory the downloaded packs. Run first; later steps discover files from its output.

Writes art/reports/inspect.json (via the runner) and inspect.md, copies licence texts to
art/licenses/<pack>.txt and refreshes the generated block in CREDITS.md.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.append(str(Path(__file__).resolve().parent))

from lib.discovery import LICENSE_RX, MODEL_EXTS, load_packs_config, walk_files  # noqa: E402
from lib.report import Report  # noqa: E402
from lib.step import Ctx, run_step  # noqa: E402

SAMPLES_PER_PACK = 3
CREDITS_START = "<!-- packs:start (generated by pnpm art:inspect) -->"
CREDITS_END = "<!-- packs:end -->"


def sample_model(path: Path) -> dict[str, object]:
    """Import one model into an empty scene and describe it."""
    import bpy

    from lib.scene import armatures, bone_names, deform_bone_count, import_model, meshes, reset_scene
    from lib.scene import triangle_count, world_bounds

    reset_scene()
    objs = import_model(path)
    lo, hi = world_bounds(objs)
    arms = armatures(objs)
    return {
        "objects": [{"name": o.name, "type": o.type, "parent": o.parent.name if o.parent else None} for o in objs],
        "triangles": sum(triangle_count(o) for o in meshes(objs)),
        "dimensionsM": [round(hi[i] - lo[i], 3) for i in range(3)],
        "minZ": round(lo[2], 3),
        "materials": sorted({m.name for o in meshes(objs) for m in o.data.materials if m}),
        "armatures": [
            {"name": a.name, "bones": bone_names(a), "deformBones": deform_bone_count(a)} for a in arms
        ],
        "actions": [
            {"name": a.name, "frames": [round(a.frame_range[0], 2), round(a.frame_range[1], 2)]}
            for a in bpy.data.actions
        ],
    }


def pick_samples(models: list[Path]) -> list[Path]:
    """A few representative files: full bodies and animation libraries first, then the first glTFs."""
    gl = [m for m in models if m.suffix.lower() in (".glb", ".gltf")]
    key = [m for m in gl if "fullbody" in m.stem.lower() or m.stem.lower().startswith("ual")]
    rest = [m for m in gl if m not in key]
    return key + rest[: max(0, SAMPLES_PER_PACK - len(key))]


def update_credits(repo: Path, lines: list[str]) -> None:
    path = repo / "CREDITS.md"
    block = "\n".join([CREDITS_START, *lines, CREDITS_END])
    if path.exists():
        text = path.read_text(encoding="utf-8")
        if CREDITS_START in text and CREDITS_END in text:
            head, rest = text.split(CREDITS_START, 1)
            tail = rest.split(CREDITS_END, 1)[1]
            text = head + block + tail
        else:
            text = text.rstrip() + "\n\n## Art packs\n\n" + block + "\n"
    else:
        text = (
            "# Credits\n\nShipFair uses these free asset packs. CC0 needs no credit, but we give it anyway.\n"
            "Licence texts are copied to `art/licenses/`.\n\n## Art packs\n\n" + block + "\n"
        )
    path.write_text(text, encoding="utf-8")


def main(ctx: Ctx, report: Report) -> None:
    packs_cfg = load_packs_config(ctx.art)
    report.info(f"packs dir: {ctx.packs}")
    if not ctx.packs.is_dir():
        report.error(f"ART_PACKS_DIR does not exist: {ctx.packs}")
        return
    present = sorted(e.name for e in ctx.packs.iterdir() if e.is_dir())
    packs: dict[str, dict[str, object]] = {}
    credits: list[str] = []
    lic_dir = ctx.art / "licenses"
    lic_dir.mkdir(parents=True, exist_ok=True)
    md = ["# Pack inventory", "", f"Packs dir: `{ctx.packs}`", ""]

    for cfg in packs_cfg:
        pid = cfg["id"]
        root = ctx.packs / pid
        if not root.is_dir():
            packs[pid] = {"found": False, "required": cfg.get("required", False)}
            (report.error if cfg.get("required") else report.warn)(f"pack missing: {pid}")
            md += [f"## {pid}: MISSING", ""]
            continue
        files = list(walk_files(root))
        models = [f for f in files if f.suffix.lower() in MODEL_EXTS]
        licenses = [f for f in files if LICENSE_RX.match(f.name) and f.suffix.lower() in (".txt", ".md", "")]
        by_ext: dict[str, int] = {}
        for m in models:
            by_ext[m.suffix.lower()] = by_ext.get(m.suffix.lower(), 0) + 1
        samples = []
        for path in pick_samples(models):
            rel = str(path.relative_to(ctx.packs)).replace("\\", "/")
            report.info(f"sampling {rel}")
            try:
                samples.append({"path": rel, **sample_model(path)})
            except Exception as exc:  # noqa: BLE001 - one bad file must not stop the inventory
                report.warn(f"could not sample {rel}: {exc}")
        if licenses:
            texts = [f"== {f.relative_to(root)} ==\n{f.read_text(encoding='utf-8', errors='replace')}" for f in licenses]
            (lic_dir / f"{pid}.txt").write_text("\n\n".join(texts), encoding="utf-8")
        else:
            report.warn(f"{pid}: no licence file found; record its licence ({cfg.get('license')}) by hand")
        packs[pid] = {
            "found": True,
            "required": cfg.get("required", False),
            "models": [{"path": str(m.relative_to(root)).replace("\\", "/"), "ext": m.suffix.lower()} for m in models],
            "modelCounts": by_ext,
            "licenseFiles": [str(f.relative_to(root)).replace("\\", "/") for f in licenses],
            "samples": samples,
        }
        licence_note = (
            f"Licence: `art/licenses/{pid}.txt`"
            if licenses
            else f"Licence: {cfg['license']} per the pack page (the download has no licence file)"
        )
        credits.append(f"- **{cfg['title']}** by {cfg['author']} ({cfg['license']}), {cfg['url']}. {licence_note}")
        md += [f"## {pid}", "", f"- models: {by_ext}", f"- licence files: {[str(f.name) for f in licenses]}"]
        for s in samples:
            arms = s["armatures"]
            md.append(
                f"- sample `{s['path']}`: {s['triangles']} tris, dims {s['dimensionsM']} m, "
                f"materials {s['materials']}, bones {[a['deformBones'] for a in arms]}, actions {len(s['actions'])}"
            )
        md.append("")

    unknown = [p for p in present if p not in packs]
    if unknown:
        report.warn(f"folders in ART_PACKS_DIR not listed in art/config/packs.json: {unknown}")
    update_credits(ctx.repo, credits)
    found = [p for p, v in packs.items() if v["found"]]
    missing = [p for p, v in packs.items() if not v["found"]]
    report.stats.update({"packsDir": str(ctx.packs), "found": found, "missing": missing, "packs": packs})
    (ctx.reports / "inspect.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    report.info(f"found {len(found)} packs: {found}; missing: {missing}")


if __name__ == "__main__":
    run_step(main)
