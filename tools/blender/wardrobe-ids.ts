// `pnpm art:ids`: wardrobe/hair manifests + palettes -> packages/shared/src/generated/wardrobe-ids.ts,
// so AvatarStyle v2 rejects ids and colour indices that the art build didn't produce.
// Pure: reads nothing itself; run.ts passes the parsed files in. Output matches Biome's formatting.
import { z } from 'zod';

const LINE_WIDTH = 100;

const manifestItem = z.object({
  id: z.string().regex(/^[a-z0-9_]{1,32}$/),
  slot: z.string().optional(),
  hidesHair: z.boolean().optional(),
  hidesHairMask: z.number().int().optional(),
  capIncompatible: z.boolean().optional(),
  unlock: z.string().nullable().optional(),
});
export const manifestSchema = z.object({ items: z.array(manifestItem) });
export const paletteSchema = z.object({
  colors: z.array(z.object({ hex: z.string().regex(/^#[0-9a-fA-F]{6}$/) })).min(1),
  harmonyGroups: z.array(z.object({ id: z.string(), colors: z.array(z.int()) })).optional(),
});

export interface IdsInput {
  bodies: string[];
  wardrobe: z.infer<typeof manifestSchema>;
  hair: z.infer<typeof manifestSchema>;
  facial: z.infer<typeof manifestSchema>;
  headwear: z.infer<typeof manifestSchema>;
  skin: z.infer<typeof paletteSchema>;
  hairColors: z.infer<typeof paletteSchema>;
  palette: z.infer<typeof paletteSchema>;
}

const quote = (s: string) => `'${s}'`;

/** `export const NAME = [a, b] as const;` on one line when it fits, else one item per line. */
export function constArray(name: string, items: string[], asConst = true): string {
  const tail = asConst ? ' as const;' : ';';
  const one = `export const ${name} = [${items.join(', ')}]${tail}`;
  if (one.length <= LINE_WIDTH) return one;
  return `export const ${name} = [\n${items.map((i) => `  ${i},`).join('\n')}\n]${tail}`;
}

function constRecord(name: string, type: string, entries: [string, string][]): string {
  const body = entries.map(([k, v]) => `${k}: ${quote(v)}`).join(', ');
  const one = `export const ${name}: ${type} = { ${body} };`;
  if (entries.length === 0) return `export const ${name}: ${type} = {};`;
  if (one.length <= LINE_WIDTH) return one;
  return `export const ${name}: ${type} = {\n${entries.map(([k, v]) => `  ${k}: ${quote(v)},`).join('\n')}\n};`;
}

const ids = (
  m: z.infer<typeof manifestSchema>,
  keep: (i: z.infer<typeof manifestItem>) => boolean = () => true,
) => m.items.filter(keep).map((i) => i.id);

export function renderWardrobeIds(input: IdsInput): string {
  const slot = (s: string) => ids(input.wardrobe, (i) => i.slot === s);
  const groups = input.palette.harmonyGroups ?? [];
  const n = input.palette.colors.length;
  for (const g of groups) {
    if (g.colors.some((c) => c < 0 || c >= n))
      throw new Error(`harmony group ${g.id} indexes past ${n} colours`);
  }
  const unlocks = [
    ...input.wardrobe.items,
    ...input.hair.items,
    ...input.headwear.items,
    ...input.facial.items,
  ]
    .filter((i) => i.unlock)
    .map((i): [string, string] => [i.id, i.unlock as string]);
  const lines = [
    '// Generated by `pnpm art:ids` from art/export/*/manifest.json and art/palette/*.json. Do not edit.',
    '',
    constArray('BODY_IDS', input.bodies.map(quote)),
    constArray('TOP_IDS', slot('top').map(quote)),
    constArray('BOTTOM_IDS', slot('bottom').map(quote)),
    constArray('SHOES_IDS', slot('shoes').map(quote)),
    constArray('ACCESSORY_IDS', slot('accessory').map(quote)),
    constArray('HAIR_IDS', ids(input.hair).map(quote)),
    constArray('FACIAL_IDS', ids(input.facial).map(quote)),
    constArray('HEADWEAR_IDS', ids(input.headwear).map(quote)),
    '/** Headwear that hides all hair (the hair choice is kept for when it comes off). */',
    constArray('HEADWEAR_HIDES_HAIR', ids(input.headwear, (i) => i.hidesHair === true).map(quote)),
    '/** Headwear that hides part of the hair (crown etc.); clashes with capIncompatible hair. */',
    constArray(
      'HEADWEAR_PARTIAL',
      ids(input.headwear, (i) => !i.hidesHair && (i.hidesHairMask ?? 0) > 0).map(quote),
    ),
    constArray(
      'CAP_INCOMPATIBLE_HAIR',
      ids(input.hair, (i) => i.capIncompatible === true).map(quote),
    ),
    `export const SKIN_COUNT = ${input.skin.colors.length};`,
    `export const HAIR_COLOR_COUNT = ${input.hairColors.colors.length};`,
    `export const PALETTE_COUNT = ${n};`,
    constArray(
      'SKIN_HEX',
      input.skin.colors.map((c) => quote(c.hex.toLowerCase())),
    ),
    constArray(
      'HAIR_HEX',
      input.hairColors.colors.map((c) => quote(c.hex.toLowerCase())),
    ),
    constArray(
      'PALETTE_HEX',
      input.palette.colors.map((c) => quote(c.hex.toLowerCase())),
    ),
    '/** Clothing colour groups that look good together (indices into PALETTE_HEX). */',
    constArray(
      'HARMONY_GROUPS: readonly (readonly number[])[]',
      groups.map((g) => `[${g.colors.join(', ')}]`),
      false,
    ),
    constRecord('UNLOCKS', 'Readonly<Record<string, string>>', unlocks),
    '',
  ];
  return lines.join('\n');
}
